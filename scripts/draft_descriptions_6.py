def build() -> dict:
    out = {}
    problems = []
    for c in INDEX:
        en = c["en"]
        draft = DRAFTS.get(en)
        if not draft:
            problems.append(f"缺草稿：{en}")
            continue
        own = set(c["whitelist"])
        for field in ("tagline", "intro", "build"):
            text = draft[field]
            for name in re.findall(r"\{([^}]+)\}", text):
                if name not in own:
                    problems.append(f"{en}.{field}: 牌名不在本主将清单 → {name}")
            def sub(m):
                name = m.group(1)
                zh = ZH.get(name)
                return f"{zh}（{name}）" if zh else name
            out.setdefault(en, {})[field] = re.sub(r"\{([^}]+)\}", sub, text)
    if problems:
        print("✗ 草稿问题：")
        for p in problems:
            print("   -", p)
        raise SystemExit(1)
    return out


def report(data: dict) -> None:
    CJK = re.compile(r"[\u4e00-\u9fff]")
    rows = []
    for en, v in data.items():
        for f in ("intro", "build"):
            s = v[f]
            rows.append((en, f, len(re.sub(r"\s", "", s)), len(CJK.findall(s))))
    for en, f, t, c in rows:
        flag = ""
        if f == "intro" and not (70 <= t <= 120):
            flag = "  ← 超"
        if f == "build" and not (110 <= t <= 170):
            flag = "  ← 超"
        print(f"{en:<34}{f:<7}非空格 {t:>4}  汉字 {c:>4}{flag}")


if __name__ == "__main__":
    data = build()
    (DATA / "descriptions_6.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"写出 {len(data)} 条 → descriptions_6.json\n")
    report(data)
